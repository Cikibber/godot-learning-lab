import { LESSONS, SURVEYS } from "@/content";
import { lessonContent, surveyContent } from "@/lib/validation/content";

export const CONTENT_MIGRATION = "supabase/migrations/20261013000004_content_v1.sql";

const lit = (v: unknown) => `'${JSON.stringify(v).replaceAll("'", "''")}'::jsonb`;

/** Idempotent inserts; existing (key, version) rows are never modified. */
export function contentSql(): string {
  const out = ["-- GENERATED by `npm run content:sql` from content/. Do not edit by hand.", ""];
  for (const raw of LESSONS) {
    const l = lessonContent.parse(raw);
    out.push(
      `insert into public.lesson_versions (lesson_key, version, module_no, activity_kind, content) values ('${l.key}', ${l.version}, ${l.module}, '${l.kind}', ${lit(l)}) on conflict (lesson_key, version) do nothing;`,
    );
  }
  for (const raw of SURVEYS) {
    const s = surveyContent.parse(raw);
    out.push(
      `insert into public.survey_versions (survey_key, version, content) values ('${s.key}', ${s.version}, ${lit(s)}) on conflict (survey_key, version) do nothing;`,
    );
  }
  return out.join("\n") + "\n";
}
